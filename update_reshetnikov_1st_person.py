# Застосовуємо оновлення зі збереженням шрифту Times New Roman 14 pt Justify
for p_idx, new_text in replacements.items():
    if p_idx < len(doc.paragraphs):
        p = doc.paragraphs[p_idx]
        # Очищуємо текст та встановлюємо заново в першому run
        for r in p.runs:
            r.text = ''
        if len(p.runs) == 0:
            run = p.add_run(new_text)
        else:
            run = p.runs[0]
            run.text = new_text
            
        run.font.name = 'Times New Roman'
        run.font.size = docx.shared.Pt(14)
        run.bold = False
        run.italic = False
        p.alignment = docx.enum.text.WD_ALIGN_PARAGRAPH.JUSTIFY
        p.paragraph_format.first_line_indent = docx.shared.Inches(0.492)
        p.paragraph_format.line_spacing = 1.5

